/**
 * Process record inside the repo: orqen/work/<KEY>/
 *
 *   state.json                   projection of the current state (the operational source of truth is cli/.state)
 *   log.md                       one line per transition
 *   round-N/support.md|json      first-line outcome (SUPPORT_STAGE=on): reply to the client or escalation to the analyst
 *   round-N/analysis.md|json     what was decided in the grilling: summary, criteria, decisions, lane, SIS
 *   round-N/execution/           script, steps, rollback and verification of the operational lane
 *   round-N/devel-pr.md          explanation of the PR to the devel branch (`orqen pr`)
 *   round-N/code-review-<n>.md   code review reports for the senior (`orqen review`), one per review
 *
 * It is committed together with the REC branch, so traceability sits next to the code and the spec.
 * Writing here must never break the process: errors are logged and processing continues.
 */
import { appendFileSync, mkdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import type { Rec } from "./store.ts";

export class Factory {
  constructor(private dir: string) {}

  dirOf = (key: string) => join(this.dir, key);
  roundDir = (key: string, round: number) => join(this.dir, key, `round-${round}`);

  private safe(fn: () => void) {
    try { fn(); } catch (e) { console.error(`[orqen] warning: could not write to orqen/work/: ${(e as Error).message}`); }
  }

  /** Writes `round-N/<file>` (creates the directories). */
  write(rec: Pick<Rec, "key" | "round">, file: string, content: string) {
    this.safe(() => {
      const f = join(this.roundDir(rec.key, rec.round), file);
      mkdirSync(join(f, ".."), { recursive: true });
      writeFileSync(f, content);
    });
  }

  /** Log line + state projection. */
  record(rec: Rec, from: string, to: string, detail: string, agent?: string) {
    this.safe(() => {
      mkdirSync(this.dirOf(rec.key), { recursive: true });
      appendFileSync(join(this.dirOf(rec.key), "log.md"),
        `- ${new Date().toISOString()} · ${from} → ${to}${detail ? ` · ${detail.replace(/\s+/g, " ")}` : ""}${agent ? ` · (${agent})` : ""}\n`);
      writeFileSync(join(this.dirOf(rec.key), "state.json"), JSON.stringify({
        _note: "Informational projection generated by `orqen`. The source of truth is cli/.state.",
        key: rec.key, state: to, round: rec.round, route: rec.route, lane: rec.lane, analyst: rec.analyst,
        sis: rec.sis, branch: rec.branch || undefined, change: rec.change || undefined,
        updated: new Date().toISOString(),
      }, null, 2) + "\n");
    });
  }
}
