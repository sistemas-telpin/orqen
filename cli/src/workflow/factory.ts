/**
 * The worq of a request (orqen's unit of work) inside the repo: orqen/worqs/<KEY>/
 *
 *   state.json                   snapshot of the whole request at its last transition: what orqen recovers from when another
 *                                machine (or a deleted orqen/state) has no record of it
 *   log.md                       one line per transition
 *   round-N/support.md|json      first-line outcome: reply to the client or escalation to the analyst
 *   round-N/analysis.md|json     what was decided in the grilling: summary, criteria, decisions, lane, issue
 *   round-N/execution/           script, steps, rollback and verification of the operational lane
 *   round-N/devel-pr.md          explanation of the PR to the devel branch (`orqen pr`)
 *   round-N/qa-review-<n>.md     QA decisions with their report (`orqen review`, full lane only)
 *   round-N/code-review-<n>.md   code review reports for the senior (`orqen code-review`), one per review
 *
 * It is committed together with the request branch, so traceability sits next to the code and the spec.
 * Writing here must never break the process: errors are logged and processing continues.
 */
import { appendFileSync, mkdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import type { WorkItem } from "./store.ts";
import type { Comment } from "../connectors/types.ts";

export class Factory {
  constructor(private dir: string) {}

  dirOf = (key: string) => join(this.dir, key);
  roundDir = (key: string, round: number) => join(this.dir, key, `round-${round}`);

  conversation(key: string, comments: Comment[]) {
    const dir = this.dirOf(key);
    mkdirSync(dir, { recursive: true });
    writeFileSync(join(dir, "conversation.json"), JSON.stringify({ request: key, comments }, null, 2) + "\n");
  }

  private safe(fn: () => void) {
    try { fn(); } catch (e) { console.error(`[orqen] warning: could not write to the worqs folder: ${(e as Error).message}`); }
  }

  /** Writes `round-N/<file>` (creates the directories). */
  write(rec: Pick<WorkItem, "key" | "round">, file: string, content: string) {
    this.safe(() => {
      const f = join(this.roundDir(rec.key, rec.round), file);
      mkdirSync(join(f, ".."), { recursive: true });
      writeFileSync(f, content);
    });
  }

  /** Log line + state projection. */
  record(rec: WorkItem, from: string, to: string, detail: string, agent?: string) {
    this.safe(() => {
      mkdirSync(this.dirOf(rec.key), { recursive: true });
      appendFileSync(join(this.dirOf(rec.key), "log.md"),
        `- ${new Date().toISOString()} · ${from} → ${to}${detail ? ` · ${detail.replace(/\s+/g, " ")}` : ""}${agent ? ` · (${agent})` : ""}\n`);
      // everything but the lock (it belongs to one machine and one agent)
      const { lock: _lock, recovered: _recovered, ...snapshot } = rec;
      writeFileSync(join(this.dirOf(rec.key), "state.json"), JSON.stringify({
        _note: "Snapshot generated by `orqen` at the last transition. If this machine has no record of the request, orqen recovers it from here.",
        ...snapshot, state: to, updated: new Date().toISOString(),
      }, null, 2) + "\n");
    });
  }
}
