/**
 * Request records stored under orqen/work/<KEY>/.
 *
 *   status.json                 Current state projection. Authoritative state is in orqen/state.
 *   history.md                  A line per workflow transition.
 *   round-N/analysis.md|json    Analysis summary, criteria, decisions, lane, and SIS.
 *   round-N/execution/          Operational script, steps, rollback, and verification.
 *
 * Records are committed alongside the code and specification on the request branch.
 * Record write failures are logged so the workflow can continue.
 */
import { appendFileSync, existsSync, mkdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import type { Rec } from "./store.ts";

const PREVIOUS_NAMES: Record<string, string> = {
  "analysis.json": "analisis.json",
  "analysis.md": "analisis.md",
  "execution/summary.md": "ejecucion/resumen.md",
  "execution/script.sql": "ejecucion/script.sql",
  "execution/steps.md": "ejecucion/pasos.md",
  "execution/rollback.txt": "ejecucion/rollback.txt",
  "execution/verification.txt": "ejecucion/verificacion.txt",
};

function recordPath(directory: string, filename: string, previous?: string): string {
  const current = join(directory, filename);
  if (!previous || existsSync(current)) return current;
  const old = join(directory, previous);
  return existsSync(old) ? old : current;
}

export class Factory {
  constructor(private dir: string) {}

  dirDe = (key: string) => join(this.dir, key);
  roundDir = (rec: Pick<Rec, "key" | "ronda">) =>
    recordPath(this.dirDe(rec.key), `round-${rec.ronda}`, `ronda-${rec.ronda}`);

  artifactPath(rec: Pick<Rec, "key" | "ronda">, filename: string): string {
    return recordPath(this.roundDir(rec), filename, PREVIOUS_NAMES[filename]);
  }

  private seguro(fn: () => void) {
    try { fn(); } catch (e) { console.error(`[orqen] warning: could not write to orqen/work/: ${(e as Error).message}`); }
  }

  /** Write a round artifact, creating directories as needed. */
  escribir(rec: Pick<Rec, "key" | "ronda">, archivo: string, contenido: string) {
    this.seguro(() => {
      const f = this.artifactPath(rec, archivo);
      mkdirSync(dirname(f), { recursive: true });
      writeFileSync(f, contenido);
    });
  }

  /** Append a transition and write the current state projection. */
  registrar(rec: Rec, desde: string, hacia: string, detalle: string, agente?: string) {
    this.seguro(() => {
      mkdirSync(this.dirDe(rec.key), { recursive: true });
      appendFileSync(recordPath(this.dirDe(rec.key), "history.md", "bitacora.md"),
        `- ${new Date().toISOString()} · ${desde} → ${hacia}${detalle ? ` · ${detalle.replace(/\s+/g, " ")}` : ""}${agente ? ` · (${agente})` : ""}\n`);
      writeFileSync(recordPath(this.dirDe(rec.key), "status.json", "estado.json"), JSON.stringify({
        _nota: "Informational record generated by orqen. Authoritative state is in orqen/state.",
        key: rec.key, estado: hacia, ronda: rec.ronda, via: rec.via, carril: rec.carril, analista: rec.analista,
        sis: rec.sis, rama: rec.rama || undefined, cambio: rec.cambio || undefined,
        actualizado: new Date().toISOString(),
      }, null, 2) + "\n");
    });
  }
}
